-- THE USER'S DICTIONARIES, COMMON TO EVERY CONTENT TYPE: the tags of every site of every type as the
-- user merges, names, puts under others, binds to the entries of a catalogue and ignores; and the
-- dictionary of universes with their characters. Moved here from the corrections of each type
-- (typecorrections V1-V18), where they were kept apart for books and games.

-- --- Tags ---

-- A normalized tag: what the sites' tags bound to it are, one tag of the user's. [name] the user's
-- name of it; [ignored] — kept with its works, not read by the models of the grades
CREATE TABLE normalized_tag (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(1000),
    ignored BOOLEAN DEFAULT FALSE NOT NULL
);

-- Every tag of every site — the site's own key of it — and the normalized tag it is
CREATE TABLE site_tag (
    source     VARCHAR(100)             NOT NULL,
    tag        VARCHAR(500)             NOT NULL,
    normalized BIGINT                   NOT NULL REFERENCES normalized_tag (id),
    bound_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (source, tag)
);
CREATE INDEX site_tag_normalized ON site_tag (normalized);

-- A tag under another: a work with the child has the parent too
CREATE TABLE normalized_tag_parent (
    child     BIGINT                   NOT NULL REFERENCES normalized_tag (id) ON DELETE CASCADE,
    parent    BIGINT                   NOT NULL REFERENCES normalized_tag (id) ON DELETE CASCADE,
    linked_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (child, parent)
);

-- Two tags the user told apart: never offered as one again; the smaller id first
CREATE TABLE normalized_tag_distinct (
    first_tag BIGINT                   NOT NULL REFERENCES normalized_tag (id) ON DELETE CASCADE,
    other_tag BIGINT                   NOT NULL REFERENCES normalized_tag (id) ON DELETE CASCADE,
    said_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (first_tag, other_tag)
);

-- A tag merged into another whose answers on the works are still to be moved
CREATE TABLE normalized_tag_merge (
    from_tag  BIGINT                   NOT NULL PRIMARY KEY,
    into_tag  BIGINT                   NOT NULL,
    merged_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- An entry of a catalogue of tags (Wikidata) as it was read, its texts by language
CREATE TABLE tag_entry (
    catalogue     VARCHAR(100)             NOT NULL,
    entry         VARCHAR(100)             NOT NULL,
    url           VARCHAR(1000)            NOT NULL,
    fetched_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    above_read_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (catalogue, entry)
);

-- The labels (kind L), aliases (A) and descriptions (D) of an entry, in their order
CREATE TABLE tag_entry_text (
    catalogue VARCHAR(100)  NOT NULL,
    entry     VARCHAR(100)  NOT NULL,
    language  VARCHAR(20)   NOT NULL,
    kind      CHAR(1)       NOT NULL,
    position  INT           NOT NULL,
    text      VARCHAR(2000) NOT NULL,
    PRIMARY KEY (catalogue, entry, language, kind, position),
    FOREIGN KEY (catalogue, entry) REFERENCES tag_entry (catalogue, entry) ON DELETE CASCADE
);

-- The entries an entry is a kind of, by the catalogue
CREATE TABLE tag_entry_above (
    catalogue VARCHAR(100) NOT NULL,
    entry     VARCHAR(100) NOT NULL,
    above     VARCHAR(100) NOT NULL,
    PRIMARY KEY (catalogue, entry, above)
);

-- The entries a tag is bound to, by the user
CREATE TABLE normalized_tag_entry (
    tag       BIGINT                   NOT NULL REFERENCES normalized_tag (id) ON DELETE CASCADE,
    catalogue VARCHAR(100)             NOT NULL,
    entry     VARCHAR(100)             NOT NULL,
    bound_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (tag, catalogue, entry)
);
CREATE INDEX normalized_tag_entry_entry ON normalized_tag_entry (catalogue, entry);

-- What every tag without a name of the user's is shown by, worked out of the names of its works'
-- tags on the sites: the most used among the works liked, the graded, all, the first by the
-- alphabet ([rule] says which). Made again as the works and their grades change
CREATE TABLE tag_shown_name (
    tag  BIGINT        PRIMARY KEY,
    name VARCHAR(1000) NOT NULL,
    rule VARCHAR(20)   NOT NULL
);

-- --- Universes ---

-- A universe of the dictionary: an entry of a catalogue (Wikidata) the user added, as last read
CREATE TABLE universe (
    catalogue    VARCHAR(100)             NOT NULL,
    universe_id  VARCHAR(100)             NOT NULL,
    name         VARCHAR(1000)            NOT NULL,
    description  VARCHAR(2000),
    url          VARCHAR(2000)            NOT NULL,
    added_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    refreshed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    labels       CLOB,
    descriptions CLOB,
    languages    VARCHAR(200),
    properties   VARCHAR(1000),
    PRIMARY KEY (catalogue, universe_id)
);

-- What else the catalogue says of a universe, property by property
CREATE TABLE universe_property (
    catalogue      VARCHAR(100)  NOT NULL,
    universe_id    VARCHAR(100)  NOT NULL,
    property       VARCHAR(100)  NOT NULL,
    property_value VARCHAR(2000) NOT NULL,
    PRIMARY KEY (catalogue, universe_id, property, property_value),
    FOREIGN KEY (catalogue, universe_id) REFERENCES universe (catalogue, universe_id) ON DELETE CASCADE
);

-- A character of a universe, as the catalogue names it
CREATE TABLE universe_character (
    catalogue    VARCHAR(100)  NOT NULL,
    universe_id  VARCHAR(100)  NOT NULL,
    character_id VARCHAR(100)  NOT NULL,
    names        CLOB          NOT NULL,
    description  VARCHAR(2000),
    url          VARCHAR(2000) NOT NULL,
    sex          VARCHAR(20),
    labels       CLOB,
    aliases      CLOB,
    descriptions CLOB,
    PRIMARY KEY (catalogue, universe_id, character_id),
    FOREIGN KEY (catalogue, universe_id) REFERENCES universe (catalogue, universe_id) ON DELETE CASCADE
);

-- What else the catalogue says of a character, property by property
CREATE TABLE universe_character_property (
    catalogue      VARCHAR(100)  NOT NULL,
    universe_id    VARCHAR(100)  NOT NULL,
    character_id   VARCHAR(100)  NOT NULL,
    property       VARCHAR(100)  NOT NULL,
    property_value VARCHAR(2000) NOT NULL,
    PRIMARY KEY (catalogue, universe_id, character_id, property, property_value),
    FOREIGN KEY (catalogue, universe_id, character_id) REFERENCES universe_character (catalogue, universe_id, character_id) ON DELETE CASCADE
);

-- The classes of the catalogue a character is an instance of
CREATE TABLE universe_character_class (
    catalogue    VARCHAR(100) NOT NULL,
    universe_id  VARCHAR(100) NOT NULL,
    character_id VARCHAR(100) NOT NULL,
    class_id     VARCHAR(100) NOT NULL,
    PRIMARY KEY (catalogue, universe_id, character_id, class_id),
    FOREIGN KEY (catalogue, universe_id, character_id) REFERENCES universe_character (catalogue, universe_id, character_id) ON DELETE CASCADE
);

-- A class of the catalogue, and whether its instances are characters
CREATE TABLE universe_class (
    catalogue    VARCHAR(100)  NOT NULL,
    class_id     VARCHAR(100)  NOT NULL,
    name         VARCHAR(1000) NOT NULL,
    is_character BOOLEAN       NOT NULL,
    labels       CLOB,
    PRIMARY KEY (catalogue, class_id)
);

-- The user's word on a class of a universe: its instances are its characters, or not
CREATE TABLE universe_class_choice (
    catalogue   VARCHAR(100) NOT NULL,
    universe_id VARCHAR(100) NOT NULL,
    class_id    VARCHAR(100) NOT NULL,
    included    BOOLEAN      NOT NULL,
    PRIMARY KEY (catalogue, universe_id, class_id),
    FOREIGN KEY (catalogue, universe_id) REFERENCES universe (catalogue, universe_id) ON DELETE CASCADE
);

-- The user's word on one character of a universe: it is one, or not
CREATE TABLE universe_character_choice (
    catalogue    VARCHAR(100) NOT NULL,
    universe_id  VARCHAR(100) NOT NULL,
    character_id VARCHAR(100) NOT NULL,
    included     BOOLEAN      NOT NULL,
    PRIMARY KEY (catalogue, universe_id, character_id),
    FOREIGN KEY (catalogue, universe_id) REFERENCES universe (catalogue, universe_id) ON DELETE CASCADE
);

-- The name the user gives an entry of a catalogue in the interface's language
CREATE TABLE universe_local_name (
    catalogue VARCHAR(100)             NOT NULL,
    entry_id  VARCHAR(200)             NOT NULL,
    name      VARCHAR(1000)            NOT NULL,
    named_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (catalogue, entry_id)
);

-- --- The move ---

-- The files of the types whose tags and universes were moved here: a start that stopped after the
-- copy and before their tables were dropped does not copy them twice
CREATE TABLE dictionary_moved (
    owner    VARCHAR(200)             PRIMARY KEY,
    moved_at TIMESTAMP WITH TIME ZONE NOT NULL
);
